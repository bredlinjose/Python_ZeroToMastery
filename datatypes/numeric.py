a = 5  # int
print("Type of a: ", type(a))
b = 5.0  # float
print("Type of b: ", type(b))
c = 2 + 4j  # complex
print("Type of c: ", type(c))

d = int("100")  # from string  # o/p: 100
e = int(3.9)    # from float  # o/p: 3
f = int(True)   # from boolean  # o/p: 1

print(abs(-18))  # 18
print(pow(2, 3))  # 8
print(divmod(10, 3))  # (3,1)
print(round(3.6))  # 4
print(isinstance(19, int))  # True
